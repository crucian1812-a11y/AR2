namespace Koenig
{
    // Проводник путешествия — кот-профессор Кёня. Модель собрана нами в
    // tools/blender/build_guide.py и лежит в Resources/Models/monsters,
    // поэтому грузится тем же CharacterModel.Spawn, что и остальные
    // персонажи (id "GuideCat", гуманоидный риг, все семь клипов).
    //
    // Реплики держим здесь, а не в контенте точек: это голос спутника, он
    // общий на всё путешествие, а точки — про конкретные места.
    public static class Guide
    {
        public const string ModelId = "GuideCat";
        public const string Name = "Кёня";

        public const string Intro =
            "Мяу! Я Кёня, кот-проводник. Когда-то в Кёнигсберге было семь " +
            "мостов, и никто не мог обойти их все по разу. Соберём подсказки " +
            "по всей области — и в конце, в Калининграде, разгадаем эту тайну!";

        public const string Finale =
            "Вот и Калининград — здесь всё и решится. Разложим карту, " +
            "сосчитаем мосты у каждого угла и починим прогулку. Ты готов?";

        // Короткое слово при въезде в каждый город.
        public static string ForCity(string cityId)
        {
            if (cityId == "zeln") return "Зеленоградск, город кошек — мой родной! Отсюда и начнём.";
            if (cityId == "svtl") return "Светлогорск. У моря учат считать чётность — это ключ к загадке.";
            if (cityId == "bltk") return "Балтийск, самый запад. Здесь возьмём последние жетоны мостов.";
            if (cityId == "klgd") return Finale;
            return "";
        }
    }
}
