#!/usr/bin/env python3
"""Проводник игры-путешествия: кубический кот-профессор «Кёня».

Путешествие начинается в Зеленоградске — городе кошек, — поэтому и
проводник кот. Ведёт ребёнка по области, выдаёт задания и объясняет
задачу о мостах. Собственный персонаж, не хомлин: хомлины — авторское
IP, здесь ни их дизайн, ни имена не используются.

Стоит на двух лапах в тех же пропорциях, что и герои (32 «пикселя» от
земли, гуманоидный скелет), поэтому берёт готовый риг и все семь клипов
из build_hero даром — коту-проводнику хватит Idle, но пусть умеет и
ходить рядом. Кошачье добавлено кубиками: уши, мордочка, хвост; учёная
шапочка и сумка для артефактов подсказывают, что он проводник.

Запуск:
    python3 tools/blender/build_guide.py

Готовый FBX кладётся в unity/Assets/Resources/Models/monsters/GuideCat.fbx.
"""

import os
import sys

try:
    import bpy  # noqa: F401
except ImportError:
    sys.exit("Нужен пакет bpy: python3 -m pip install --break-system-packages bpy")

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_assets import material  # noqa: E402
from build_hero import PX, assemble, export, part, reset  # noqa: E402


def mat(name, rgb, rough=0.7, metal=0.0):
    return material(name, rgb, rough, metal)


def guide():
    m = {
        "fur":   mat("catFur",   (0.80, 0.43, 0.14)),   # рыжий кот
        "furD":  mat("catFurD",  (0.55, 0.27, 0.09)),   # тень/полоски
        "white": mat("catWhite", (0.93, 0.92, 0.88)),   # мордочка, лапки
        "pink":  mat("catPink",  (0.92, 0.55, 0.58)),   # нос, уши изнутри
        "eye":   mat("catEye",   (0.30, 0.72, 0.36)),   # зелёные глаза
        "cap":   mat("catCap",   (0.16, 0.32, 0.62)),   # синяя шапочка
        "capD":  mat("catCapD",  (0.11, 0.22, 0.45)),
        "bag":   mat("catBag",   (0.42, 0.28, 0.15)),   # сумка для артефактов
        "gold":  mat("catGold",  (0.86, 0.68, 0.20), 0.4, 0.3),
        "black": mat("catBlack", (0.06, 0.06, 0.08)),
    }
    p = []

    # --- ноги (0..12), белые «носочки» снизу ---
    for sx, bone in ((1, "Leg.L"), (-1, "Leg.R")):
        x = sx * 2 * PX
        part(bone, (x, 0, 6 * PX), (2 * PX, 2 * PX, 6 * PX), m["fur"], p)
        part(bone, (x, 0, 1.4 * PX), (2.1 * PX, 2.1 * PX, 1.4 * PX), m["white"], p)

    # --- корпус (12..24) ---
    part("Spine", (0, 0, 18 * PX), (4 * PX, 2 * PX, 6 * PX), m["fur"], p)
    # Светлая грудка и живот
    part("Spine", (0, -2.05 * PX, 17 * PX), (2.6 * PX, 0.3 * PX, 5 * PX), m["white"], p)
    # Тёмные полоски на спине — по ним кот читается котом, а не медведем
    for z in (14, 17, 20):
        part("Spine", (0, 2.05 * PX, z * PX), (2.8 * PX, 0.3 * PX, 0.5 * PX), m["furD"], p)

    # --- сумка проводника на боку + ремень через грудь ---
    part("Spine", (4.2 * PX, 1.6 * PX, 15 * PX), (1.1 * PX, 1.4 * PX, 1.8 * PX), m["bag"], p)
    part("Spine", (4.3 * PX, 1.6 * PX, 16.2 * PX), (1.15 * PX, 1.0 * PX, 0.4 * PX), m["gold"], p)
    for zz in (16, 18, 20, 22):
        part("Spine", ((zz - 19) * 0.9 * PX, -2.1 * PX, zz * PX),
             (0.4 * PX, 0.3 * PX, 0.9 * PX), m["bag"], p)

    # --- руки-лапы (12..24), белые перчатки-лапки ---
    for sx, bone in ((1, "Arm.L"), (-1, "Arm.R")):
        x = sx * 6 * PX
        part(bone, (x, 0, 18 * PX), (2 * PX, 2 * PX, 6 * PX), m["fur"], p)
        part(bone, (x, 0, 13 * PX), (2.1 * PX, 2.1 * PX, 1.8 * PX), m["white"], p)

    # --- голова (24..32) ---
    part("Head", (0, 0, 28 * PX), (4 * PX, 4 * PX, 4 * PX), m["fur"], p)
    # Светлая мордочка
    part("Head", (0, -4.05 * PX, 26.4 * PX), (2.6 * PX, 0.35 * PX, 2.0 * PX), m["white"], p)
    # Большие зелёные глаза с чёрным зрачком
    for sx in (-1, 1):
        part("Head", (sx * 1.9 * PX, -4.1 * PX, 29.0 * PX),
             (1.1 * PX, 0.25 * PX, 1.1 * PX), m["eye"], p)
        part("Head", (sx * 1.9 * PX, -4.25 * PX, 29.0 * PX),
             (0.4 * PX, 0.2 * PX, 0.7 * PX), m["black"], p)
    # Розовый нос и рот
    part("Head", (0, -4.2 * PX, 27.0 * PX), (0.55 * PX, 0.25 * PX, 0.45 * PX), m["pink"], p)
    part("Head", (0, -4.15 * PX, 26.0 * PX), (1.2 * PX, 0.2 * PX, 0.25 * PX), m["furD"], p)
    # Усы — тонкие белые бруски по сторонам мордочки
    for sx in (-1, 1):
        for i in (0, 1):
            part("Head", (sx * 3.4 * PX, -4.1 * PX, (26.8 - i * 0.9) * PX),
                 (1.6 * PX, 0.12 * PX, 0.12 * PX), m["white"], p)
    # Уши: высокие кубики на передних углах макушки, розовые изнутри.
    # Именно они держат силуэт кота, поэтому торчат ВЫШЕ шапочки.
    for sx in (-1, 1):
        part("Head", (sx * 2.7 * PX, -0.6 * PX, 33.4 * PX),
             (1.2 * PX, 1.3 * PX, 2.2 * PX), m["fur"], p)
        part("Head", (sx * 2.7 * PX, -1.7 * PX, 33.2 * PX),
             (0.6 * PX, 0.3 * PX, 1.2 * PX), m["pink"], p)

    # --- маленькая шапочка проводника, сдвинута назад между ушей ---
    part("Head", (0, 1.4 * PX, 32.3 * PX), (2.9 * PX, 2.4 * PX, 0.5 * PX), m["capD"], p)
    part("Head", (0, 1.6 * PX, 33.2 * PX), (2.1 * PX, 2.0 * PX, 1.2 * PX), m["cap"], p)
    part("Head", (0, 2.2 * PX, 34.6 * PX), (0.5 * PX, 0.5 * PX, 0.6 * PX), m["gold"], p)

    # --- хвост: кубики от бёдер назад и вверх, крючком ---
    # y растёт наружу от спины (задняя грань корпуса на 2 px), потом
    # хвост загибается вверх крючком. Прошлый хвост жался к спине на 2.6 px
    # и читался гребнем, а не хвостом.
    # Хвост уводим ВБОК дугой (растёт x), иначе при x=0 он сидит ровно
    # за корпусом и с фронта-три-четверти полностью закрыт. Уходит вправо
    # и вверх, поднимаясь выше плеча — так его видно с любого угла.
    tail = [
        (0.0, 4.0, 10.5, 1.15),
        (0.9, 6.6, 11.4, 1.05),
        (2.4, 8.4, 13.2, 0.98),
        (4.0, 9.0, 15.8, 0.92),
        (5.2, 8.8, 18.8, 0.9),
        (5.8, 8.0, 21.8, 0.88),
        (5.6, 6.8, 24.2, 0.85),
    ]
    for (tx, ty, tz, r) in tail:
        part("Hips", (tx * PX, ty * PX, tz * PX),
             (r * PX, r * PX, r * PX), m["fur"], p)
    # Белый кончик хвоста, высоко и сбоку — заметен отовсюду
    part("Hips", (5.0 * PX, 5.6 * PX, 25.8 * PX), (0.82 * PX, 0.82 * PX, 0.95 * PX), m["white"], p)

    return p


def main():
    reset()
    assemble("GuideCat", guide())
    export("GuideCat")


if __name__ == "__main__":
    main()
